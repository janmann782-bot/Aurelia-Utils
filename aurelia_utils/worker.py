"""Run separately: python -m aurelia_utils.worker. Exactly one worker per data dir."""
import fcntl
import hashlib
import json
import logging
import os
import signal
import time
import zipfile
from dataclasses import asdict
from pathlib import Path

from PIL import Image
from .config import Config
from .engine import (Params, geography, render_field, render_sketch, inspect_image,
                     preview_mask, sketch_mask, sketch_field, ENGINE_VERSION)
from .store import Store

log = logging.getLogger(__name__)


def usage(path):
    return sum(p.stat().st_size for p in Path(path).rglob('*') if p.is_file())


def check_quota(config, user, reserve=0):
    if usage(config.user_dir(user)) + reserve > config.user_bytes:
        raise ValueError("Место закончилось. Удали ненужные карты через меню")
    if usage(config.root) + reserve > config.total_bytes:
        raise ValueError("Хранилище сервера заполнено")


def job_dir(config, user, job):
    # IDs are generated by the server; still reject untrusted callback strings.
    if len(job) != 16 or any(c not in '0123456789abcdef' for c in job):
        raise ValueError("Некорректный ID")
    directory = config.user_dir(user) / job
    directory.mkdir(parents=True, exist_ok=True)
    return directory


def run_job(config, store, job):
    out = job_dir(config, job['user'], job['id'])
    data = json.loads(job['params'])
    last = [0.0]
    start = time.monotonic()

    def progress(stage, done=0, total=0):
        now = time.monotonic()
        if now-start > config.job_seconds:
            raise TimeoutError("Задача шла слишком долго. Выбери размер поменьше")
        if now-last[0] >= .4 or done == total:
            store.progress(job['id'], stage, done, total)
            last[0] = now

    check_quota(config, job['user'], reserve=12_000_000)
    if job['kind'] == 'inspect':
        progress("Читаю пятно")
        size = inspect_image(out / 'source')
        # Always retain the uploaded bytes unchanged.
        meta = {"source_size": size, "source_sha256": hashlib.sha256((out/'source').read_bytes()).hexdigest()}
        for polarity in ('dark', 'light'):
            try:
                preview_mask(out/'source', out/f'{polarity}.png', polarity, data.get('threshold', 128))
                meta[polarity] = True
            except ValueError:
                meta[polarity] = False
        if not meta.get('dark') and not meta.get('light'):
            raise ValueError("Не вижу пятна суши. Нужны 2 различающиеся области")
        (out/'metadata.json').write_text(json.dumps(meta, ensure_ascii=False, indent=2))
    else:
        params = Params(**data['params'])
        params.validate()
        preview_width = min(params.width, 1280)
        preview_height = max(32, round(params.height*preview_width/params.width))
        if job['kind'] == 'seed':
            field = geography(params, progress)
            share = render_field(field, params.width, params.height, out/'map.png', progress)
            # Do not decode 16K PNG simply to get a small preview.
            render_field(field, preview_width, preview_height, out/'preview.png')
        elif job['kind'] == 'sketch':
            parent = store.get(data['source_job'], job['user'])
            if not parent or parent['kind'] != 'inspect' or parent['status'] != 'ready':
                raise ValueError("Исходник не найден")
            source = job_dir(config, job['user'], parent['id']) / 'source'
            share = render_sketch(source, params, out/'map.png', data['polarity'],
                                  data.get('threshold', 128), data['mode'], progress)
            # Preview from resulting geography would require a full output decode.
            # Use a nearest downsample of the source for strict mode, same field for coast.
            if data['mode'] == 'strict':
                preview_mask(source, out/'preview.png', data['polarity'], data.get('threshold',128))
            else:
                mask = sketch_mask(source, data['polarity'], data.get('threshold',128))
                field = sketch_field(mask,params)
                render_field(field, preview_width, preview_height, out/'preview.png')
        else:
            raise ValueError("Неизвестная задача")
        progress("Сохраняю результат")
        meta = {"engine": ENGINE_VERSION, "kind": job['kind'], "params": asdict(params),
                "land_pixel_share": share, "colors": {"land":"#FFFFFF", "water":"#2470CA"},
                "note": "Доля пикселей суши, не геодезическая площадь", "request": data}
        (out/'metadata.json').write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding='utf-8')
        with zipfile.ZipFile(out/'project.zip.part', 'w', zipfile.ZIP_DEFLATED) as archive:
            archive.write(out/'map.png', 'map.png')
            archive.write(out/'metadata.json', 'metadata.json')
            if job['kind'] == 'sketch':
                archive.write(source, 'original/source')
        os.replace(out/'project.zip.part', out/'project.zip')
    check_quota(config, job['user'])
    store.finish(job['id'])


def main():
    logging.basicConfig(level=logging.INFO, format='%(asctime)s %(levelname)s %(message)s')
    config = Config.env()
    store = Store(config.root)
    with (config.root/'worker.lock').open('w') as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise SystemExit("Worker already running for this DATA_DIR")
        store.recover()
        stopping = [False]
        signal.signal(signal.SIGTERM, lambda *_: stopping.__setitem__(0, True))
        signal.signal(signal.SIGINT, lambda *_: stopping.__setitem__(0, True))
        while not stopping[0]:
            job = store.claim()
            if not job:
                time.sleep(.5)
                continue
            try:
                run_job(config, store, job)
            except InterruptedError:
                folder = job_dir(config,job['user'],job['id'])
                for path in folder.iterdir():
                    if path.name != 'source':
                        path.unlink(missing_ok=True)
                store.acknowledge_cancel(job['id'])
            except Exception as e:
                # Never log bot credentials or Telegram request URLs.
                log.error("Job %s failed: %s", job['id'], type(e).__name__)
                message = str(e) if isinstance(e, (ValueError, TimeoutError)) else "Обработка прервалась. Исходник сохранен. Попробуй еще раз"
                store.finish(job['id'], message)
                folder = job_dir(config,job['user'],job['id'])
                # Retain original uploads, remove incomplete generated artifacts.
                for name in ('map.png','preview.png','project.zip','project.zip.part','map.png.part'):
                    (folder/name).unlink(missing_ok=True)


if __name__ == '__main__':
    main()
